/*
 * Extracts the DTS core constant tables verbatim from FFmpeg's sources into dts_tables.h.
 *
 * They are large and purely numeric, and transcribing them by hand would be a good way to
 * introduce a silent one-digit bug, so the port generates them instead. Re-run only when
 * re-basing on a newer FFmpeg:
 *
 *   node extract_tables.mjs <dir holding dcadata.c, dcahuff.c>
 *
 * Pinned to FFmpeg n9.0.2, as dts_decode.cpp is. The generated header is committed, so a normal
 * build does not need FFmpeg's tree.
 */
import fs from "node:fs";
import path from "node:path";

const SRC = process.argv[2];
const read = (file) => fs.readFileSync(path.join(SRC, file), "utf8");

const stripComments = (text) => text.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "");

/** The `{...}` initializer of `symbol`, comments gone. */
function initializer(source, symbol)
{
	const at = source.search(new RegExp("\\b" + symbol + "\\b\\)?(\\[[^\\]]*\\])*\\s*=\\s*\\{"));
	if (at < 0) {
		throw new Error("no " + symbol);
	}
	const open = source.indexOf("{", at);
	let depth = 0;
	for (let i = open; ; ++i) {
		if (source[i] === "{") {
			++depth;
		} else if (source[i] === "}" && --depth === 0) {
			return source.slice(open, i + 1).replace(/[ \t]+$/gm, "").replace(/\n{2,}/g, "\n");
		}
	}
}

const dcadata = stripComments(read("dcadata.c"));
const dcahuff = stripComments(read("dcahuff.c"));

const lines = [
	"/*",
	"	DTS core constant tables, generated by extract_tables.mjs from FFmpeg's libavcodec/dcadata.c",
	"	and libavcodec/dcahuff.c (n9.0.2, LGPL-2.1-or-later; see dts_decode.cpp for the notice).",
	"	Do not edit by hand.",
	"*/",
	"",
	"#ifndef DTS_TABLES_H",
	"#define DTS_TABLES_H",
	"",
];

const emit = (source, type, symbol, dims) =>
	lines.push("static const " + type + " " + symbol + dims + " = " + initializer(source, symbol) + ";", "");

emit(dcadata, "uint32_t", "ff_dca_bit_rates", "[32]");
emit(dcadata, "uint8_t", "ff_dca_channels", "[16]");
emit(dcadata, "uint8_t", "ff_dca_quant_index_sel_nbits", "[10]");
emit(dcadata, "uint8_t", "ff_dca_quant_index_group_size", "[10]");
emit(dcadata, "int16_t", "ff_dca_adpcm_vb", "[4096][4]");
emit(dcadata, "uint32_t", "ff_dca_scale_factor_quant6", "[64]");
emit(dcadata, "uint32_t", "ff_dca_scale_factor_quant7", "[128]");
emit(dcadata, "uint32_t", "ff_dca_joint_scale_factors", "[129]");
emit(dcadata, "uint32_t", "ff_dca_scale_factor_adj", "[4]");
emit(dcadata, "uint32_t", "ff_dca_quant_levels", "[32]");
emit(dcadata, "uint32_t", "ff_dca_lossy_quant", "[32]");
emit(dcadata, "uint32_t", "ff_dca_lossless_quant", "[32]");
emit(dcadata, "int8_t", "ff_dca_high_freq_vq", "[1024][32]");
emit(dcadata, "float", "ff_dca_fir_32bands_perfect", "[512]");
emit(dcadata, "float", "ff_dca_fir_32bands_nonperfect", "[512]");
lines.push("#define SCALE(c) ((c) / (256.0f * 32768.0f))");
emit(dcadata, "float", "ff_dca_lfe_fir_64", "[256]");
emit(dcadata, "float", "ff_dca_lfe_fir_128", "[256]");
lines.push("#undef SCALE", "");

emit(dcahuff, "uint8_t", "bitalloc_12_vlc_bits", "[5]");
emit(dcahuff, "uint8_t", "ff_dca_bitalloc_sizes", "[10]");
emit(dcahuff, "int8_t", "ff_dca_bitalloc_offsets", "[10]");
emit(dcahuff, "uint8_t", "bitalloc_maxbits", "[10][7]");
// {symbol, length} rows, the core's code books first (the rows past them are DTS Express's).
emit(dcahuff, "uint8_t", "ff_dca_vlc_src_tables", "[][2]");

lines.push("#endif", "");
fs.writeFileSync(path.join(import.meta.dirname, "dts_tables.h"), lines.join("\n"));
