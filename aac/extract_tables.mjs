/*
 * Extracts the AAC constant tables verbatim from FFmpeg's sources into aac_tables.h.
 *
 * They are large and purely numeric, and transcribing them by hand would be a good way to
 * introduce a silent one-digit bug, so the port generates them instead. Re-run only when
 * re-basing on a newer FFmpeg:
 *
 *   node extract_tables.mjs <dir holding aactab.c, aacdec_tab.c, channel_layout.h>
 *
 * The generated header is committed, so a normal build does not need FFmpeg's tree.
 */
import fs from "node:fs";
import path from "node:path";

const SRC = process.argv[2];
const read = (file) => fs.readFileSync(path.join(SRC, file), "utf8");

const stripComments = (text) => text.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "");

/** The `{...}` initializer of `symbol`, comments gone. */
function initializer(source, symbol)
{
	const at = source.search(new RegExp("\\b" + symbol + "\\b(\\)?\\[[^\\]]*\\])*\\s*=\\s*\\{?"));
	if (at < 0) {
		throw new Error("no " + symbol);
	}
	const open = source.indexOf("{", at);
	let depth = 0;
	for (let i = open; ; ++i) {
		if (source[i] === "{") {
			++depth;
		} else if (source[i] === "}" && --depth === 0) {
			return source.slice(open, i + 1).replace(/[ \t]+$/gm, "").replace(/\n{2,}/g, "\n");
		}
	}
}

const aactab = stripComments(read("aactab.c"));
const aacdecTab = stripComments(read("aacdec_tab.c"));
const layout = stripComments(read("channel_layout.h"));

const lines = [
	"/*",
	"	AAC constant tables, generated by extract_tables.mjs from FFmpeg's libavcodec/aactab.c,",
	"	libavcodec/aac/aacdec_tab.c and libavutil/channel_layout.h (n8.1, LGPL-2.1-or-later;",
	"	see aac_decode.cpp for the notice). Do not edit by hand.",
	"*/",
	"",
	"#ifndef AAC_TABLES_H",
	"#define AAC_TABLES_H",
	"",
];

// The channel ids, and the layout masks built from them (sniff_channel_order sorts on the bits).
const channels = layout.match(/enum AVChannel \{([\s\S]*?)\};/)[1]
	.split("\n").map((line) => line.trim()).filter((line) => /^AV_CHAN_/.test(line));
lines.push("enum AVChannel {", ...channels.map((line) => "\t" + line), "};", "");
for (const [, name, value] of layout.matchAll(/^#define (AV_CH_\w+)\s+(.+)$/gm)) {
	lines.push("#define " + name + " " + value.trim());
}
lines.push("");

const emit = (source, type, symbol, dims = "[]", name = symbol) =>
	lines.push("static const " + type + " " + name + dims + " = " + initializer(source, symbol) + ";", "");

for (const map of ["tns_tmp2_map_1_3", "tns_tmp2_map_0_3", "tns_tmp2_map_1_4", "tns_tmp2_map_0_4"]) {
	emit(aactab, "float", map);
}
lines.push("static const float *const ff_tns_tmp2_map[4] = {",
	"	tns_tmp2_map_0_3, tns_tmp2_map_0_4, tns_tmp2_map_1_3, tns_tmp2_map_1_4,", "};", "");

emit(aactab, "uint8_t", "ff_aac_num_swb_1024");
emit(aactab, "uint8_t", "ff_aac_num_swb_128");
emit(aactab, "uint32_t", "ff_aac_scalefactor_code");
emit(aactab, "uint8_t", "ff_aac_scalefactor_bits");

for (let book = 1; book <= 11; ++book) {
	emit(aactab, "uint16_t", "codes" + book);
	emit(aactab, "uint8_t", "bits" + book);
}
const books = Array.from({length: 11}, (_, index) => index + 1);
lines.push("static const uint16_t *const ff_aac_spectral_codes[11] = { " + books.map((book) => "codes" + book).join(", ") + " };");
lines.push("static const uint8_t *const ff_aac_spectral_bits[11] = { " + books.map((book) => "bits" + book).join(", ") + " };", "");
emit(aactab, "uint16_t", "ff_aac_spectral_sizes", "[11]");

for (const vals of ["codebook_vector0_vals", "codebook_vector4_vals", "codebook_vector10_vals"]) {
	emit(aactab, "float", vals);
}
for (const idx of ["codebook_vector02_idx", "codebook_vector4_idx", "codebook_vector6_idx", "codebook_vector8_idx", "codebook_vector10_idx"]) {
	emit(aactab, "uint16_t", idx);
}
emit(aactab, "float *const", "ff_aac_codebook_vector_vals");
emit(aactab, "uint16_t *const", "ff_aac_codebook_vector_idx");

for (const rate of [96, 64, 48, 32, 24, 16, 8]) {
	emit(aactab, "uint16_t", "swb_offset_1024_" + rate);
}
for (const rate of [96, 48, 24, 16, 8]) {
	emit(aactab, "uint16_t", "swb_offset_128_" + rate);
}
emit(aactab, "uint16_t *const", "ff_swb_offset_1024");
emit(aactab, "uint16_t *const", "ff_swb_offset_128");
emit(aactab, "uint8_t", "ff_tns_max_bands_1024");
emit(aactab, "uint8_t", "ff_tns_max_bands_128");

emit(aacdecTab, "int8_t", "ff_tags_per_config", "[16]");
emit(aacdecTab, "uint8_t", "ff_aac_channel_layout_map", "[16][16][3]");
emit(aacdecTab, "int16_t", "ff_aac_channel_map", "[3][4][6]");

lines.push("#endif", "");
fs.writeFileSync(path.join(import.meta.dirname, "aac_tables.h"), lines.join("\n"));
