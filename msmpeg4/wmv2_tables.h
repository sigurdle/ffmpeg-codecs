static inline int wmv2_get_cbp_table_index(int qscale, int cbp_index)
{
    static const uint8_t map[3][3] = {
        { 0, 2, 1 },
        { 1, 0, 2 },
        { 2, 1, 0 },
    };

    return map[(qscale > 10) + (qscale > 20)][cbp_index];
}

