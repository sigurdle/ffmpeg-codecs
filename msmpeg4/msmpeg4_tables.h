// ── slow VLC: prefix-exact incremental decode for the long-code (code,len) tables ─
// Avoids huge flat LUTs for the DC (26-bit) and inter-MB-type (21-bit) tables,
// which are read only ~1x/block or ~1x/MB. Reads bit-by-bit, returns the symbol
// index of the matching prefix-free (code,len) pair (-1 if none).
static inline int msm_vlc_slow(mp4::GetBits* gb, const uint32_t (*table)[2], int n, int maxlen) {
    uint32_t code = 0;
    for (int len = 1; len <= maxlen; len++) {
        code = (code << 1) | mp4::get_bits1(gb);
        for (int i = 0; i < n; i++)
            if ((int)table[i][1] == len && table[i][0] == code) return i;
    }
    return -1;
}
static inline int msm_dc_vlc(mp4::GetBits* gb, const uint32_t table[120][2]) {
    return msm_vlc_slow(gb, table, 120, 26);
}

// Build a flat single-level VLC LUT from CODE LENGTHS (canonical assignment, the
// ff_vlc_init_from_lengths algorithm): codes are handed out MSB-aligned in table
// order, code += 1<<(32-len) per symbol. `syms` gives the returned symbol per entry
// (NULL -> the index). Used for the MV tables (given as symbol+length, no codes).
static inline void msm_build_vlc_from_lengths(mp4::VLCElem* table, int bits, int nb_codes,
                                              const uint8_t* lens, const uint16_t* syms) {
    int size = 1 << bits;
    for (int i = 0; i < size; i++) { table[i].sym = -1; table[i].len = 0; }
    uint32_t code = 0;
    for (int i = 0; i < nb_codes; i++) {
        int len = lens[i];
        if (len <= 0) continue;
        uint32_t c = code >> (32 - len);
        int base = (int)(c << (bits - len)), nb = 1 << (bits - len);
        int sym = syms ? syms[i] : i;
        for (int k = 0; k < nb; k++) { table[base + k].sym = (int16_t)sym; table[base + k].len = (int16_t)len; }
        code += 1u << (32 - len);
    }
}

