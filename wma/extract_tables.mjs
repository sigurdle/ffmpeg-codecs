/*
 * Extracts the WMA v1/v2 constant tables verbatim from FFmpeg's sources into wma_tables.h.
 *
 * They are large and purely numeric, and transcribing them by hand would be a good way to
 * introduce a silent one-digit bug, so the port generates them instead. Re-run only when
 * re-basing on a newer FFmpeg:
 *
 *   node extract_tables.mjs <dir holding wmadata.h, wma_freqs.c, aactab.c>
 *
 * Pinned to FFmpeg n9.0.2, as wma_decode.cpp is. The generated header is committed, so a normal
 * build does not need FFmpeg's tree.
 */
import fs from "node:fs";
import path from "node:path";

const SRC = process.argv[2];
const read = (file) => fs.readFileSync(path.join(SRC, file), "utf8");

const stripComments = (text) => text.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "");

/** The `{...}` initializer of `symbol`, comments gone. */
function initializer(source, symbol)
{
	const at = source.search(new RegExp("\\b" + symbol + "\\b(\\[[^\\]]*\\])*\\s*=\\s*\\{"));
	if (at < 0) {
		throw new Error("no " + symbol);
	}
	const open = source.indexOf("{", at);
	let depth = 0;
	for (let i = open; ; ++i) {
		if (source[i] === "{") {
			++depth;
		} else if (source[i] === "}" && --depth === 0) {
			return source.slice(open, i + 1).replace(/[ \t]+$/gm, "").replace(/\n{2,}/g, "\n");
		}
	}
}

const wmadata = stripComments(read("wmadata.h"));
const freqs = stripComments(read("wma_freqs.c"));
const aactab = stripComments(read("aactab.c"));

const lines = [
	"/*",
	"	WMA v1/v2 constant tables, generated by extract_tables.mjs from FFmpeg's libavcodec/wmadata.h,",
	"	libavcodec/wma_freqs.c and libavcodec/aactab.c (n9.0.2, LGPL-2.1-or-later; see wma_decode.cpp",
	"	for the notice). Do not edit by hand.",
	"*/",
	"",
	"#ifndef WMA_TABLES_H",
	"#define WMA_TABLES_H",
	"",
];

const emit = (source, type, symbol, dims = "[]") =>
	lines.push("static const " + type + " " + symbol + dims + " = " + initializer(source, symbol) + ";", "");

for (const rate of [22050, 32000, 44100]) {
	emit(wmadata, "uint8_t", "exponent_band_" + rate, "[3][25]");
}
emit(wmadata, "uint8_t", "ff_wma_hgain_hufftab", "[37][2]");
emit(wmadata, "float", "ff_wma_lsp_codebook", "[NB_LSP_COEFS][16]");
for (let table = 0; table < 6; ++table) {
	emit(wmadata, "uint32_t", "coef" + table + "_huffcodes");
	emit(wmadata, "uint8_t", "coef" + table + "_huffbits");
}
for (let table = 0; table < 6; ++table) {
	emit(wmadata, "uint16_t", "levels" + table);
}
emit(freqs, "uint16_t", "ff_wma_critical_freqs", "[25]");
emit(aactab, "uint32_t", "ff_aac_scalefactor_code", "[121]");
emit(aactab, "uint8_t", "ff_aac_scalefactor_bits", "[121]");

lines.push("#endif", "");
fs.writeFileSync(path.join(import.meta.dirname, "wma_tables.h"), lines.join("\n"));
