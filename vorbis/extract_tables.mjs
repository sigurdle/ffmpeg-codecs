/*
 * Extracts the Vorbis constant tables verbatim from FFmpeg's libavcodec/vorbis_data.c into vorbis_tables.h: the windows, the
 * floor 1 inverse dB table and the channel order.
 *
 * Re-run only when re-basing on a newer FFmpeg; the generated header is committed, so a normal build does not need FFmpeg's tree:
 *
 *   node extract_tables.mjs <path of vorbis_data.c>
 */
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const source = fs.readFileSync(process.argv[2], "utf8");
const output = path.join(path.dirname(fileURLToPath(import.meta.url)), "vorbis_tables.h");

/** The `{...}` initializer following the declaration `head`. */
function initializer(head)
{
	const at = source.indexOf(head);
	if (at < 0) {
		throw new Error("no " + head);
	}
	const open = source.indexOf("{", at + head.length);
	let depth = 0;
	for (let i = open; ; ++i) {
		if (source[i] === "{") {
			++depth;
		} else if (source[i] === "}" && --depth === 0) {
			return source.slice(open, i + 1);
		}
	}
}

const lines = [
	"// Generated by extract_tables.mjs from FFmpeg n8.1 libavcodec/vorbis_data.c (LGPL-2.1+). Do not edit.",
	"",
	"#pragma once",
	"",
	`static const uint8_t ff_vorbis_channel_layout_offsets[8][8] = ${initializer("ff_vorbis_channel_layout_offsets[8][8] =")};`,
	"",
];
for (const size of [64, 128, 256, 512, 1024, 2048, 4096, 8192]) {
	lines.push(`static const float vwin${size}[${size / 2}] = ${initializer(`vwin${size})[${size / 2}] =`)};`, "");
}
lines.push(
	`static const float ff_vorbis_floor1_inverse_db_table[256] = ${initializer("ff_vorbis_floor1_inverse_db_table[256]=")};`,
	"",
	"static const float* const ff_vorbis_vwin[8] = { vwin64, vwin128, vwin256, vwin512, vwin1024, vwin2048, vwin4096, vwin8192 };",
	"",
);
fs.writeFileSync(output, lines.join("\n"));
