static inline int av_log2_16bit(unsigned v)
{
	int n = 0;
	if (v & 0xff00) {
		v >>= 8;
		n += 8;
	}
	while (v > 1) {	// ff_log2_tab[v] for v < 256
		v >>= 1;
		n++;
	}
	return n;
}

static inline unsigned av_zero_extend(unsigned a, unsigned p) { return a & ((1U << p) - 1); }

static inline void wb16(uint8_t *p, unsigned v) { p[0] = (uint8_t)(v >> 8); p[1] = (uint8_t)v; }
static inline void wb32(uint8_t *p, uint32_t v) { p[0] = (uint8_t)(v >> 24); p[1] = (uint8_t)(v >> 16); p[2] = (uint8_t)(v >> 8); p[3] = (uint8_t)v; }

// ---------------------------------------------------------------- put_bits.h (BUF_BITS 64, big-endian)

typedef uint64_t BitBuf;
#define BUF_BITS 64

struct PutBitContext {
	BitBuf bit_buf;
	int bit_left;
	uint8_t *buf, *buf_ptr, *buf_end;
};

static inline void init_put_bits(PutBitContext *s, uint8_t *buffer, int buffer_size)
{
	if (buffer_size < 0) {
		buffer_size = 0;
		buffer = NULL;
	}
	s->buf = buffer;
	s->buf_end = s->buf + buffer_size;
	s->buf_ptr = s->buf;
	s->bit_left = BUF_BITS;
	s->bit_buf = 0;
}

static inline void wbbuf(uint8_t *p, BitBuf v)
{
	for (int i = 0; i < 8; i++)
		p[i] = (uint8_t)(v >> (56 - 8 * i));
}

static inline void put_bits(PutBitContext *s, int n, BitBuf value)
{
	BitBuf bit_buf = s->bit_buf;
	int bit_left = s->bit_left;

	if (n < bit_left) {
		bit_buf = (bit_buf << n) | value;
		bit_left -= n;
	} else {
		bit_buf <<= bit_left;
		bit_buf |= value >> (n - bit_left);
		if (s->buf_end - s->buf_ptr >= (ptrdiff_t)sizeof(BitBuf)) {
			wbbuf(s->buf_ptr, bit_buf);
			s->buf_ptr += sizeof(BitBuf);
		}
		bit_left += BUF_BITS - n;
		bit_buf = value;
	}

	s->bit_buf = bit_buf;
	s->bit_left = bit_left;
}

static inline void flush_put_bits(PutBitContext *s)
{
	if (s->bit_left < BUF_BITS)
		s->bit_buf <<= s->bit_left;
	while (s->bit_left < BUF_BITS) {
		if (s->buf_ptr < s->buf_end)
			*s->buf_ptr++ = (uint8_t)(s->bit_buf >> (BUF_BITS - 8));
		s->bit_buf <<= 8;
		s->bit_left += 8;
	}
	s->bit_left = BUF_BITS;
	s->bit_buf = 0;
}

