// dct_quantize_c (mpegvideo_enc.c), intra with h263_aic, bias 0: the 8-bit profiles.
static int dct_quantize_c(DnxCtx *ctx, int16_t *block, int n, int qscale)
{
	int i, last_non_zero, q, start_i;
	const int *qmat;
	const uint8_t *scantable = ff_zigzag_direct;
	int bias;
	unsigned int threshold1, threshold2;

	jpeg_fdct_islow<4, 4>(block);

	q = 1 << 3;
	block[0] = (block[0] + (q >> 1)) / q;
	start_i = 1;
	last_non_zero = 0;
	qmat = n < 4 ? ctx->qmatrix_l[qscale] : ctx->qmatrix_c[qscale];
	bias = 0 * (1 << (QMAT_SHIFT - QUANT_BIAS_SHIFT));	// MPVEncContext.intra_quant_bias stays 0

	threshold1 = (1 << QMAT_SHIFT) - bias - 1;
	threshold2 = (threshold1 << 1);
	for (i = 63; i >= start_i; i--) {
		const int j = scantable[i];
		int64_t level = (int64_t)block[j] * qmat[j];

		if (((uint64_t)(level + threshold1)) > threshold2) {
			last_non_zero = i;
			break;
		} else {
			block[j] = 0;
		}
	}
	for (i = start_i; i <= last_non_zero; i++) {
		const int j = scantable[i];
		int64_t level = (int64_t)block[j] * qmat[j];

		if (((uint64_t)(level + threshold1)) > threshold2) {
			if (level > 0) {
				level = (bias + level) >> QMAT_SHIFT;
				block[j] = (int16_t)level;
			} else {
				level = (bias - level) >> QMAT_SHIFT;
				block[j] = (int16_t)-level;
			}
		} else {
			block[j] = 0;
		}
	}
	// IDCT permutation is FF_IDCT_PERM_NONE: no ff_block_permute.
	return last_non_zero;
}

static int dnxhd_10bit_dct_quantize_444(DnxCtx *ctx, int16_t *block, int n, int qscale)
{
	int i, j, level, last_non_zero, start_i;
	const int *qmat;
	const uint8_t *scantable = ff_zigzag_direct;
	int bias;
	unsigned int threshold1, threshold2;

	jpeg_fdct_islow<1, 2>(block);

	block[0] = (block[0] + 2) >> 2;
	start_i = 1;
	last_non_zero = 0;
	qmat = n < 4 ? ctx->qmatrix_l[qscale] : ctx->qmatrix_c[qscale];
	bias = 0 * (1 << (16 - 8));	// MPVEncContext.intra_quant_bias stays 0
	threshold1 = (1 << 16) - bias - 1;
	threshold2 = (threshold1 << 1);

	for (i = 63; i >= start_i; i--) {
		j = scantable[i];
		level = block[j] * qmat[j];

		if (((unsigned)(level + threshold1)) > threshold2) {
			last_non_zero = i;
			break;
		} else {
			block[j] = 0;
		}
	}

	for (i = start_i; i <= last_non_zero; i++) {
		j = scantable[i];
		level = block[j] * qmat[j];

		if (((unsigned)(level + threshold1)) > threshold2) {
			if (level > 0) {
				level = (bias + level) >> 16;
				block[j] = (int16_t)level;
			} else {
				level = (bias - level) >> 16;
				block[j] = (int16_t)-level;
			}
		} else {
			block[j] = 0;
		}
	}
	return last_non_zero;
}

static int dnxhd_10bit_dct_quantize(DnxCtx *ctx, int16_t *block, int n, int qscale)
{
	const uint8_t *scantable = ff_zigzag_direct;
	const int *qmat = n < 4 ? ctx->qmatrix_l[qscale] : ctx->qmatrix_c[qscale];
	int last_non_zero = 0;
	int i;

	jpeg_fdct_islow<1, 2>(block);

	block[0] = (block[0] + 2) >> 2;

	for (i = 1; i < 64; ++i) {
		int j = scantable[i];
		int sign = block[j] >> 15;	// FF_SIGNBIT on an int16_t
		int level = (block[j] ^ sign) - sign;
		level = level * qmat[j] >> DNX10BIT_QMAT_SHIFT;
		block[j] = (int16_t)((level ^ sign) - sign);
		if (level)
			last_non_zero = i;
	}
	return last_non_zero;
}

// ---------------------------------------------------------------- init

static int dnxhd_init_vlc(DnxCtx *ctx)
{
	int i, j, level, run;
	int max_level = 1 << (ctx->bit_depth + 2);

	ctx->orig_vlc_codes = (uint32_t *)calloc(max_level * 4, sizeof(uint32_t));
	ctx->orig_vlc_bits = (uint8_t *)calloc(max_level * 4, 1);
	ctx->run_codes = (uint16_t *)calloc(63, sizeof(uint16_t));
	ctx->run_bits = (uint8_t *)calloc(63, 1);
	if (!ctx->orig_vlc_codes || !ctx->orig_vlc_bits || !ctx->run_codes || !ctx->run_bits)
		return -1;
	ctx->vlc_codes = ctx->orig_vlc_codes + max_level * 2;
	ctx->vlc_bits = ctx->orig_vlc_bits + max_level * 2;
	for (level = -max_level; level < max_level; level++) {
		for (run = 0; run < 2; run++) {
			int index = level * (1 << 1) | run;
			int sign, offset = 0, alevel = level;

			sign = alevel >> 31;	// MASK_ABS
			alevel = (alevel ^ sign) - sign;
			if (alevel > 64) {
				offset = (alevel - 1) >> 6;
				alevel -= offset << 6;
			}
			for (j = 0; j < 257; j++) {
				if (ctx->cid_table->ac_info[2*j+0] >> 1 == alevel &&
				    (!offset || ((ctx->cid_table->ac_info[2*j+1] & 1) && offset)) &&
				    (!run    || ((ctx->cid_table->ac_info[2*j+1] & 2) && run))) {
					if (alevel) {
						ctx->vlc_codes[index] = (ctx->cid_table->ac_codes[j] << 1) | (sign & 1);
						ctx->vlc_bits[index] = ctx->cid_table->ac_bits[j] + 1;
					} else {
						ctx->vlc_codes[index] = ctx->cid_table->ac_codes[j];
						ctx->vlc_bits[index] = ctx->cid_table->ac_bits[j];
					}
					break;
				}
			}
			if (alevel && j >= 257)
				return -1;
			if (offset) {
				ctx->vlc_codes[index] = (ctx->vlc_codes[index] << ctx->cid_table->index_bits) | offset;
				ctx->vlc_bits[index] += ctx->cid_table->index_bits;
			}
		}
	}
	for (i = 0; i < 62; i++) {
		int r = ctx->cid_table->run[i];
		if (r >= 63)
			return -1;
		ctx->run_codes[r] = ctx->cid_table->run_codes[i];
		ctx->run_bits[r] = ctx->cid_table->run_bits[i];
	}
	return 0;
}

// ff_convert_matrix for the islow fdct, intra, identity permutation (only qmat is used).
static void convert_matrix(int (*qmat)[64], const uint16_t *quant_matrix, int qmin, int qmax)
{
	for (int qscale = qmin; qscale <= qmax; qscale++) {
		int qscale2 = qscale << 1;
		for (int i = 0; i < 64; i++) {
			int64_t den = (int64_t) qscale2 * quant_matrix[i];
			qmat[qscale][i] = (int)((UINT64_C(2) << QMAT_SHIFT) / den);
		}
	}
}

static int dnxhd_init_qmat(DnxCtx *ctx)
{
	uint16_t weight_matrix[64] = { 1, };
	const uint8_t *luma_weight_table = ctx->cid_table->luma_weight;
	const uint8_t *chroma_weight_table = ctx->cid_table->chroma_weight;

	ctx->qmatrix_l = (int (*)[64])calloc(QMAX + 1, sizeof(int[64]));
	ctx->qmatrix_c = (int (*)[64])calloc(QMAX + 1, sizeof(int[64]));
	if (!ctx->qmatrix_l || !ctx->qmatrix_c)
		return -1;

	if (ctx->bit_depth == 8) {
		for (int i = 1; i < 64; i++) {
			int j = ff_zigzag_direct[i];
			weight_matrix[j] = ctx->cid_table->luma_weight[i];
		}
		convert_matrix(ctx->qmatrix_l, weight_matrix, 1, QMAX);
		for (int i = 1; i < 64; i++) {
			int j = ff_zigzag_direct[i];
			weight_matrix[j] = ctx->cid_table->chroma_weight[i];
		}
		convert_matrix(ctx->qmatrix_c, weight_matrix, 1, QMAX);

		for (int qscale = 1; qscale <= QMAX; qscale++) {
			for (int i = 0; i < 64; i++) {
				ctx->qmatrix_l[qscale][i] <<= 2;
				ctx->qmatrix_c[qscale][i] <<= 2;
			}
		}
	} else {
		for (int qscale = 1; qscale <= QMAX; qscale++) {
			for (int i = 1; i < 64; i++) {
				int j = ff_zigzag_direct[i];
				ctx->qmatrix_l[qscale][j] = (1 << (DNX10BIT_QMAT_SHIFT + 1)) / (qscale * luma_weight_table[i]);
				ctx->qmatrix_c[qscale][j] = (1 << (DNX10BIT_QMAT_SHIFT + 1)) / (qscale * chroma_weight_table[i]);
			}
		}
	}
	return 0;
}

// ---------------------------------------------------------------- bitstream

static void dnxhd_write_header(DnxCtx *ctx, uint8_t *buf)
{
	memset(buf, 0, ctx->data_offset);

	wb16(buf + 0x02, ctx->data_offset);
	if (ctx->cid >= 1270 && ctx->cid <= 1274)
		buf[4] = 0x03;
	else
		buf[4] = 0x01;

	buf[5] = 0x01;	// progressive
	buf[6] = 0x80;	// crc flag off
	buf[7] = 0xa0;	// reserved
	wb16(buf + 0x18, ctx->height);	// ALPF
	wb16(buf + 0x1a, ctx->width);	// SPL
	wb16(buf + 0x1d, ctx->height);	// NAL

	buf[0x21] = ctx->bit_depth == 10 ? 0x58 : 0x38;
	buf[0x22] = 0x88;
	wb32(buf + 0x28, ctx->cid);	// CID
	buf[0x2c] = (1 << 7) | (ctx->is_444 << 6) | (ctx->is_444 ? 1 : 0);	// last bit: pix_fmt == YUV444P10

	buf[0x5f] = 0x01;	// UDL

	buf[0x167] = 0x02;	// reserved
	wb16(buf + 0x16a, ctx->mb_height * 4 + 4);	// MSIPS
	wb16(buf + 0x16c, ctx->mb_height);	// Ns
	buf[0x16f] = 0x10;	// reserved

	ctx->msip = buf + 0x170;
}

static inline void dnxhd_encode_dc(PutBitContext *pb, DnxCtx *ctx, int diff)
{
	int nbits;
	if (diff < 0) {
		nbits = av_log2_16bit(-2 * diff);
		diff--;
	} else {
		nbits = av_log2_16bit(2 * diff);
	}
	put_bits(pb, ctx->cid_table->dc_bits[nbits] + nbits,
	         (ctx->cid_table->dc_codes[nbits] << nbits) + av_zero_extend(diff, nbits));
}

static inline void dnxhd_encode_block(PutBitContext *pb, DnxCtx *ctx, int16_t *block, int last_index, int n)
{
	int last_non_zero = 0;
	int slevel, i, j;

	dnxhd_encode_dc(pb, ctx, block[0] - ctx->last_dc[n]);
	ctx->last_dc[n] = block[0];

	for (i = 1; i <= last_index; i++) {
		j = ff_zigzag_direct[i];
		slevel = block[j];
		if (slevel) {
			int run_level = i - last_non_zero - 1;
			int rlevel = slevel * (1 << 1) | !!run_level;
			put_bits(pb, ctx->vlc_bits[rlevel], ctx->vlc_codes[rlevel]);
			if (run_level)
				put_bits(pb, ctx->run_bits[run_level], ctx->run_codes[run_level]);
			last_non_zero = i;
		}
	}
	put_bits(pb, ctx->vlc_bits[0], ctx->vlc_codes[0]);	// EOB
}

static inline int dnxhd_calc_ac_bits(DnxCtx *ctx, int16_t *block, int last_index)
{
	int last_non_zero = 0;
	int bits = 0;
	int i, j, level;
	for (i = 1; i <= last_index; i++) {
		j = ff_zigzag_direct[i];
		level = block[j];
		if (level) {
			int run_level = i - last_non_zero - 1;
			bits += ctx->vlc_bits[level * (1 << 1) | !!run_level] + ctx->run_bits[run_level];
			last_non_zero = i;
		}
	}
	return bits;
}

static void dnxhd_get_blocks(DnxCtx *ctx, int mb_x, int mb_y)
{
	const int bs = ctx->block_width_l2;
	const int bw = 1 << bs;
	int dct_y_offset = ctx->dct_y_offset;
	int dct_uv_offset = ctx->dct_uv_offset;
	int linesize = ctx->linesize;
	int uvlinesize = ctx->uvlinesize;
	const uint8_t *ptr_y = ctx->src[0] + ((mb_y << 4) * ctx->linesize) + (mb_x << (bs + 1));
	const uint8_t *ptr_u = ctx->src[1] + ((mb_y << 4) * ctx->uvlinesize) + (mb_x << (bs + ctx->is_444));
	const uint8_t *ptr_v = ctx->src[2] + ((mb_y << 4) * ctx->uvlinesize) + (mb_x << (bs + ctx->is_444));
	int edge = ctx->has_edge_emu && ((mb_x << 4) + 16 > ctx->width || (mb_y << 4) + 16 > ctx->height);

	if (ctx->bit_depth != 10 && edge) {
		int y_w = ctx->width - (mb_x << 4);
		int y_h = ctx->height - (mb_y << 4);
		int uv_w = (y_w + 1) / 2;
		int uv_h = y_h;
		linesize = 16;
		uvlinesize = 8;

		emulated_edge(&ctx->edge_buf_y[0], ptr_y, linesize, ctx->linesize, linesize, 16, y_w, y_h, 1);
		emulated_edge(&ctx->edge_buf_uv[0][0], ptr_u, uvlinesize, ctx->uvlinesize, uvlinesize, 16, uv_w, uv_h, 1);
		emulated_edge(&ctx->edge_buf_uv[1][0], ptr_v, uvlinesize, ctx->uvlinesize, uvlinesize, 16, uv_w, uv_h, 1);

		dct_y_offset = bw * linesize;
		dct_uv_offset = bw * uvlinesize;
		ptr_y = &ctx->edge_buf_y[0];
		ptr_u = &ctx->edge_buf_uv[0][0];
		ptr_v = &ctx->edge_buf_uv[1][0];
	} else if (ctx->bit_depth == 10 && edge) {
		int y_w = ctx->width - (mb_x << 4);
		int y_h = ctx->height - (mb_y << 4);
		int uv_w = ctx->is_444 ? y_w : (y_w + 1) / 2;
		int uv_h = y_h;
		linesize = 32;
		uvlinesize = 16 + 16 * ctx->is_444;

		emulated_edge(&ctx->edge_buf_y[0], ptr_y, linesize, ctx->linesize, linesize / 2, 16, y_w, y_h, 2);
		emulated_edge(&ctx->edge_buf_uv[0][0], ptr_u, uvlinesize, ctx->uvlinesize, uvlinesize / 2, 16, uv_w, uv_h, 2);
		emulated_edge(&ctx->edge_buf_uv[1][0], ptr_v, uvlinesize, ctx->uvlinesize, uvlinesize / 2, 16, uv_w, uv_h, 2);

		dct_y_offset = bw * linesize / 2;
		dct_uv_offset = bw * uvlinesize / 2;
		ptr_y = &ctx->edge_buf_y[0];
		ptr_u = &ctx->edge_buf_uv[0][0];
		ptr_v = &ctx->edge_buf_uv[1][0];
	}

	if (!ctx->is_444) {
		get_pixels(ctx, ctx->blocks[0], ptr_y,      linesize);
		get_pixels(ctx, ctx->blocks[1], ptr_y + bw, linesize);
		get_pixels(ctx, ctx->blocks[2], ptr_u,      uvlinesize);
		get_pixels(ctx, ctx->blocks[3], ptr_v,      uvlinesize);

		if (mb_y + 1 == ctx->mb_height && ctx->height == 1080) {
			// progressive: the lower half of the last row is cleared
			memset(ctx->blocks[4], 0, sizeof(ctx->blocks[4]));
			memset(ctx->blocks[5], 0, sizeof(ctx->blocks[5]));
			memset(ctx->blocks[6], 0, sizeof(ctx->blocks[6]));
			memset(ctx->blocks[7], 0, sizeof(ctx->blocks[7]));
		} else {
			get_pixels(ctx, ctx->blocks[4], ptr_y + dct_y_offset, linesize);
			get_pixels(ctx, ctx->blocks[5], ptr_y + dct_y_offset + bw, linesize);
			get_pixels(ctx, ctx->blocks[6], ptr_u + dct_uv_offset, uvlinesize);
			get_pixels(ctx, ctx->blocks[7], ptr_v + dct_uv_offset, uvlinesize);
		}
	} else {
		get_pixels(ctx, ctx->blocks[0], ptr_y,      linesize);
		get_pixels(ctx, ctx->blocks[1], ptr_y + bw, linesize);
		get_pixels(ctx, ctx->blocks[6], ptr_y + dct_y_offset, linesize);
		get_pixels(ctx, ctx->blocks[7], ptr_y + dct_y_offset + bw, linesize);

		get_pixels(ctx, ctx->blocks[2], ptr_u,      uvlinesize);
		get_pixels(ctx, ctx->blocks[3], ptr_u + bw, uvlinesize);
		get_pixels(ctx, ctx->blocks[8], ptr_u + dct_uv_offset, uvlinesize);
		get_pixels(ctx, ctx->blocks[9], ptr_u + dct_uv_offset + bw, uvlinesize);

		get_pixels(ctx, ctx->blocks[4], ptr_v,      uvlinesize);
		get_pixels(ctx, ctx->blocks[5], ptr_v + bw, uvlinesize);
		get_pixels(ctx, ctx->blocks[10], ptr_v + dct_uv_offset, uvlinesize);
		get_pixels(ctx, ctx->blocks[11], ptr_v + dct_uv_offset + bw, uvlinesize);
	}
}

static inline int dnxhd_switch_matrix(DnxCtx *ctx, int i)
{
	if (ctx->is_444)
		return (i >> 1) % 3;
	static const uint8_t component[8] = { 0, 0, 1, 2, 0, 0, 1, 2 };
	return component[i];
}

static void dnxhd_calc_bits_row(DnxCtx *ctx, int mb_y)
{
	int qscale = ctx->qscale;
	int16_t block[64];
	RCEntry *rc = mb_rc(ctx, qscale);

	ctx->last_dc[0] =
	ctx->last_dc[1] =
	ctx->last_dc[2] = 1 << (ctx->bit_depth + 2);

	for (int mb_x = 0; mb_x < ctx->mb_width; mb_x++) {
		unsigned mb = mb_y * ctx->mb_width + mb_x;
		int ssd = 0;
		int ac_bits = 0;
		int dc_bits = 0;
		int i;

		dnxhd_get_blocks(ctx, mb_x, mb_y);

		for (i = 0; i < 8 + 4 * ctx->is_444; i++) {
			int16_t *src_block = ctx->blocks[i];
			int nbits, diff, last_index;
			int n = dnxhd_switch_matrix(ctx, i);

			memcpy(block, src_block, 64 * sizeof(*block));
			last_index = ctx->dct_quantize(ctx, block, ctx->is_444 ? 4 * (n > 0) : 4 & (2*i), qscale);
			ac_bits += dnxhd_calc_ac_bits(ctx, block, last_index);

			diff = block[0] - ctx->last_dc[n];
			if (diff < 0)
				nbits = av_log2_16bit(-2 * diff);
			else
				nbits = av_log2_16bit(2 * diff);

			dc_bits += ctx->cid_table->dc_bits[nbits] + nbits;

			ctx->last_dc[n] = block[0];
			// mb_decision simple and RC_VARIANCE: no unquantize / IDCT / SSD
		}
		rc[mb].ssd = ssd;
		rc[mb].bits = ac_bits + dc_bits + 12 + (1 + ctx->is_444) * 8 * ctx->vlc_bits[0];
	}
}

static void dnxhd_encode_row(DnxCtx *ctx, uint8_t *buf, int mb_y)
{
	PutBitContext pb0, *const pb = &pb0;
	init_put_bits(pb, buf + ctx->data_offset + ctx->slice_offs[mb_y], ctx->slice_size[mb_y]);

	ctx->last_dc[0] =
	ctx->last_dc[1] =
	ctx->last_dc[2] = 1 << (ctx->bit_depth + 2);
	for (int mb_x = 0; mb_x < ctx->mb_width; mb_x++) {
		unsigned mb = mb_y * ctx->mb_width + mb_x;
		int qscale = ctx->mb_qscale[mb];
		int i;

		put_bits(pb, 11, qscale);
		put_bits(pb, 1, ctx->is_444 ? 1 : 0);	// pix_fmt == YUV444P10

		dnxhd_get_blocks(ctx, mb_x, mb_y);

		for (i = 0; i < 8 + 4 * ctx->is_444; i++) {
			int16_t *block = ctx->blocks[i];
			int n = dnxhd_switch_matrix(ctx, i);
			int last_index = ctx->dct_quantize(ctx, block,
			                                   ctx->is_444 ? (((i >> 1) % 3) < 1 ? 0 : 4) : 4 & (2*i),
			                                   qscale);
			dnxhd_encode_block(pb, ctx, block, last_index, n);
		}
	}
	flush_put_bits(pb);
	memset(pb->buf_ptr, 0, pb->buf_end - pb->buf_ptr);
}

static void dnxhd_setup_threads_slices(DnxCtx *ctx)
{
	for (int mb_y = 0, offset = 0; mb_y < ctx->mb_height; mb_y++) {
		int thread_size;
		ctx->slice_offs[mb_y] = offset;
		ctx->slice_size[mb_y] = 0;
		for (int mb_x = 0; mb_x < ctx->mb_width; mb_x++) {
			unsigned mb = mb_y * ctx->mb_width + mb_x;
			ctx->slice_size[mb_y] += ctx->mb_bits[mb];
		}
		ctx->slice_size[mb_y] = (ctx->slice_size[mb_y] + 31U) & ~31U;
		ctx->slice_size[mb_y] >>= 3;
		thread_size = ctx->slice_size[mb_y];
		offset += thread_size;
	}
}

static void dnxhd_mb_var_row(DnxCtx *ctx, int mb_y)
{
	int x, y;
	int partial_last_row = (mb_y == ctx->mb_height - 1) && (ctx->height & 0xF);

	if (ctx->bit_depth == 8) {
		const uint8_t *pix = ctx->src[0] + ((mb_y << 4) * ctx->linesize);
		for (int mb_x = 0; mb_x < ctx->mb_width; ++mb_x, pix += 16) {
			unsigned mb = mb_y * ctx->mb_width + mb_x;
			int sum;
			int varc;
			// pix_sum / pix_norm1 over a whole 16x16 block equal the clipped loop
			int bw = ctx->width - 16 * mb_x < 16 ? ctx->width - 16 * mb_x : 16;
			int bh = ctx->height - 16 * mb_y < 16 ? ctx->height - 16 * mb_y : 16;
			(void)partial_last_row;
			sum = varc = 0;
			for (y = 0; y < bh; y++) {
				for (x = 0; x < bw; x++) {
					uint8_t val = pix[x + y * ctx->linesize];
					sum += val;
					varc += val * val;
				}
			}
			varc = (varc - (((unsigned) sum * sum) >> 8) + 128) >> 8;

			ctx->mb_cmp[mb].value = varc;
			ctx->mb_cmp[mb].mb = mb;
		}
	} else {
		const int linesize = ctx->linesize >> 1;
		for (int mb_x = 0; mb_x < ctx->mb_width; ++mb_x) {
			const uint16_t *pix = (const uint16_t *)ctx->src[0] + ((mb_y << 4) * linesize) + (mb_x << 4);
			unsigned mb = mb_y * ctx->mb_width + mb_x;
			int sum = 0;
			int sqsum = 0;
			int bw = ctx->width - 16 * mb_x < 16 ? ctx->width - 16 * mb_x : 16;
			int bh = ctx->height - 16 * mb_y < 16 ? ctx->height - 16 * mb_y : 16;
			int mean, sqmean;
			int i, j;
			for (i = 0; i < bh; ++i) {
				for (j = 0; j < bw; ++j) {
					// FFmpeg's "16-bit to 10-bit" shift, applied to 10-bit samples
					const int sample = (unsigned) pix[j] >> 6;
					sum += sample;
					sqsum += sample * sample;
				}
				pix += linesize;
			}
			mean = sum >> 8;
			sqmean = sqsum >> 8;
			ctx->mb_cmp[mb].value = sqmean - mean * mean;
			ctx->mb_cmp[mb].mb = mb;
		}
	}
}

static int dnxhd_find_qscale(DnxCtx *ctx)
{
	int bits = 0;
	int up_step = 1;
	int down_step = 1;
	int last_higher = 0;
	int last_lower = INT_MAX;
	int qscale;

	qscale = ctx->qscale;
	for (;;) {
		bits = 0;
		ctx->qscale = qscale;
		for (int y = 0; y < ctx->mb_height; y++)
			dnxhd_calc_bits_row(ctx, y);
		RCEntry *rc = mb_rc(ctx, qscale);
		for (int y = 0; y < ctx->mb_height; y++) {
			for (int x = 0; x < ctx->mb_width; x++)
				bits += rc[y * ctx->mb_width + x].bits;
			bits = (bits + 31) & ~31;	// padding
			if (bits > ctx->frame_bits)
				break;
		}
		if (bits < ctx->frame_bits) {
			if (qscale == 1)
				return 1;
			if (last_higher == qscale - 1) {
				qscale = last_higher;
				break;
			}
			last_lower = last_lower < qscale ? last_lower : qscale;
			if (last_higher != 0)
				qscale = (qscale + last_higher) >> 1;
			else
				qscale -= down_step++;
			if (qscale < 1)
				qscale = 1;
			up_step = 1;
		} else {
			if (last_lower == qscale + 1)
				break;
			last_higher = last_higher > qscale ? last_higher : qscale;
			if (last_lower != INT_MAX)
				qscale = (qscale + last_lower) >> 1;
			else
				qscale += up_step++;
			down_step = 1;
			if (qscale >= QMAX)
				return -1;
		}
	}
	ctx->qscale = qscale;
	return 0;
}

#define BUCKET_BITS 8
#define RADIX_PASSES 4
#define NBUCKETS (1 << BUCKET_BITS)

static inline int get_bucket(int value, int shift)
{
	value >>= shift;
	value &= NBUCKETS - 1;
	return NBUCKETS - 1 - value;
}

static void radix_count(const RCCMPEntry *data, int size, int buckets[RADIX_PASSES][NBUCKETS])
{
	int i, j;
	memset(buckets, 0, sizeof(buckets[0][0]) * RADIX_PASSES * NBUCKETS);
	for (i = 0; i < size; i++) {
		int v = data[i].value;
		for (j = 0; j < RADIX_PASSES; j++) {
			buckets[j][get_bucket(v, 0)]++;
			v >>= BUCKET_BITS;
		}
	}
	for (j = 0; j < RADIX_PASSES; j++) {
		int offset = size;
		for (i = NBUCKETS - 1; i >= 0; i--)
			buckets[j][i] = offset -= buckets[j][i];
	}
}

static void radix_sort_pass(RCCMPEntry *dst, const RCCMPEntry *data, int size, int buckets[NBUCKETS], int pass)
{
	int shift = pass * BUCKET_BITS;
	int i;
	for (i = 0; i < size; i++) {
		int v = get_bucket(data[i].value, shift);
		int pos = buckets[v]++;
		dst[pos] = data[i];
	}
}

static void radix_sort(RCCMPEntry *data, RCCMPEntry *tmp, int size)
{
	int buckets[RADIX_PASSES][NBUCKETS];
	radix_count(data, size, buckets);
	radix_sort_pass(tmp, data, size, buckets[0], 0);
	radix_sort_pass(data, tmp, size, buckets[1], 1);
	if (buckets[2][NBUCKETS - 1] || buckets[3][NBUCKETS - 1]) {
		radix_sort_pass(tmp, data, size, buckets[2], 2);
		radix_sort_pass(data, tmp, size, buckets[3], 3);
	}
}

static int dnxhd_encode_fast(DnxCtx *ctx)
{
	int max_bits = 0;
	int ret;
	if ((ret = dnxhd_find_qscale(ctx)) < 0)
		return ret;
	RCEntry *rc0 = mb_rc(ctx, ctx->qscale);
	for (int y = 0; y < ctx->mb_height; y++) {
		for (int x = 0; x < ctx->mb_width; x++) {
			int mb = y * ctx->mb_width + x;
			ctx->mb_qscale[mb] = (uint8_t)ctx->qscale;
			ctx->mb_bits[mb] = rc0[mb].bits;
			max_bits += rc0[mb].bits;
		}
		max_bits += 31;	// worst padding
	}
	if (!ret) {
		RCEntry *rc1 = mb_rc(ctx, ctx->qscale + 1);
		for (int y = 0; y < ctx->mb_height; y++)
			dnxhd_mb_var_row(ctx, y);
		radix_sort(ctx->mb_cmp, ctx->mb_cmp_tmp, ctx->mb_num);
		do {
			for (int x = 0; x < ctx->mb_num && max_bits > ctx->frame_bits; x++) {
				int mb = ctx->mb_cmp[x].mb;
				max_bits -= rc0[mb].bits - rc1[mb].bits;
				if (ctx->mb_qscale[mb] < 255)
					ctx->mb_qscale[mb]++;
				ctx->mb_bits[mb] = rc1[mb].bits;
			}
		} while (max_bits > ctx->frame_bits);	// FFmpeg's "goto retry"
	}
	return 0;
}

