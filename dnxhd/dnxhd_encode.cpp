// profile: 0 DNxHD (cid names the compression id), 1 LB, 2 SQ, 3 HQ, 4 HQX, 5 444.
// Returns a handle, or 0 when the profile / cid / size is not encodable.
DnxCtx *dnxhd_open(int profile, int cid, int width, int height)
{
	if (profile < PROFILE_DNXHD || profile > PROFILE_DNXHR_444)
		return 0;
	if (width < 256 || height < 120)
		return 0;
	if (profile != PROFILE_DNXHD)
		cid = hr_cid(profile);
	const CIDEntry *table = ff_dnxhd_get_cid_table(cid);
	if (!table)
		return 0;
	int bit_depth;
	if (profile == PROFILE_DNXHD) {
		// ff_dnxhd_find_cid: progressive, 4:2:2, its own size
		if (table->flags & (DNXHD_INTERLACED | DNXHD_444))
			return 0;
		if ((int)table->width != width || (int)table->height != height)
			return 0;
		bit_depth = table->bit_depth;
	} else {
		bit_depth = (profile == PROFILE_DNXHR_HQX || profile == PROFILE_DNXHR_444) ? 10 : 8;
	}

	DnxCtx *ctx = (DnxCtx *)calloc(1, sizeof(DnxCtx));
	if (!ctx)
		return 0;
	ctx->profile = profile;
	ctx->cid = cid;
	ctx->cid_table = table;
	ctx->bit_depth = bit_depth;
	ctx->is_444 = profile == PROFILE_DNXHR_444;
	ctx->width = width;
	ctx->height = height;
	ctx->has_edge_emu = profile != PROFILE_DNXHD;

	if (ctx->is_444 || profile == PROFILE_DNXHR_HQX) {
		ctx->dct_quantize = dnxhd_10bit_dct_quantize_444;
		ctx->block_width_l2 = 4;
	} else if (bit_depth == 10) {
		ctx->dct_quantize = dnxhd_10bit_dct_quantize;
		ctx->block_width_l2 = 4;
	} else {
		ctx->dct_quantize = dct_quantize_c;
		ctx->block_width_l2 = 3;
	}

	ctx->mb_height = (height + 15) / 16;
	ctx->mb_width = (width + 15) / 16;
	ctx->mb_num = ctx->mb_height * ctx->mb_width;

	if (table->frame_size == DNXHD_VARIABLE) {
		ctx->frame_size = ff_dnxhd_get_hr_frame_size(cid, width, height);
		ctx->coding_unit_size = ctx->frame_size;
	} else {
		ctx->frame_size = table->frame_size;
		ctx->coding_unit_size = table->coding_unit_size;
	}

	if (ctx->mb_height > 68)
		ctx->data_offset = 0x170 + (ctx->mb_height << 2);
	else
		ctx->data_offset = 0x280;

	int ok = dnxhd_init_qmat(ctx) == 0 && dnxhd_init_vlc(ctx) == 0;

	// dnxhd_init_rc
	ctx->mb_cmp = (RCCMPEntry *)calloc(ctx->mb_num, sizeof(RCCMPEntry));
	ctx->mb_cmp_tmp = (RCCMPEntry *)calloc(ctx->mb_num, sizeof(RCCMPEntry));
	ctx->frame_bits = (ctx->coding_unit_size - ctx->data_offset - 4 - ctx->min_padding) * 8;
	ctx->qscale = 1;
	ctx->lambda = 2 << LAMBDA_FRAC_BITS;

	ctx->slice_size = (uint32_t *)calloc(ctx->mb_height, sizeof(uint32_t));
	ctx->slice_offs = (uint32_t *)calloc(ctx->mb_height, sizeof(uint32_t));
	ctx->mb_bits = (uint32_t *)calloc(ctx->mb_num, sizeof(uint32_t));
	ctx->mb_qscale = (uint8_t *)calloc(ctx->mb_num, 1);

	// Input planes, rows padded to whole macroblocks (never read past the image except
	// where FFmpeg reads its own frame padding, which these zeros stand in for).
	int elem = bit_depth > 8 ? 2 : 1;
	int cw = ctx->is_444 ? width : (width + 1) / 2;
	int rows = ctx->mb_height * 16;
	ctx->plane_stride[0] = ctx->mb_width * 16 * elem;
	ctx->plane_stride[1] = ctx->plane_stride[2] = (ctx->is_444 ? ctx->mb_width * 16 : ctx->mb_width * 8) * elem;
	(void)cw;
	for (int i = 0; i < 3; i++)
		ctx->plane[i] = (uint8_t *)calloc((size_t)ctx->plane_stride[i] * rows, 1);
	ctx->packet = (uint8_t *)calloc(ctx->frame_size, 1);

	ok = ok && ctx->mb_cmp && ctx->mb_cmp_tmp && ctx->slice_size && ctx->slice_offs && ctx->mb_bits &&
	     ctx->mb_qscale && ctx->plane[0] && ctx->plane[1] && ctx->plane[2] && ctx->packet;
	if (!ok) {
		dnxhd_close(ctx);
		return 0;
	}
	return ctx;
}

void dnxhd_close(DnxCtx *ctx)
{
	if (!ctx)
		return;
	free(ctx->orig_vlc_codes);
	free(ctx->orig_vlc_bits);
	free(ctx->run_codes);
	free(ctx->run_bits);
	free(ctx->mb_bits);
	free(ctx->mb_qscale);
	for (int q = 0; q <= QMAX; q++)
		free(ctx->mb_rc_rows[q]);
	free(ctx->mb_cmp);
	free(ctx->mb_cmp_tmp);
	free(ctx->slice_size);
	free(ctx->slice_offs);
	free(ctx->qmatrix_c);
	free(ctx->qmatrix_l);
	for (int i = 0; i < 3; i++)
		free(ctx->plane[i]);
	free(ctx->rgba);
	free(ctx->packet);
	free(ctx);
}

