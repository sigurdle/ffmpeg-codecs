// A width x height x 4 RGBA16 buffer owned by the handle, for dnxhd_from_rgba16.
uint16_t *dnxhd_rgba16(DnxCtx *ctx)
{
	if (!ctx->rgba)
		ctx->rgba = (uint16_t *)malloc((size_t)ctx->width * ctx->height * 8);
	return ctx->rgba;
}

static inline int round_clamp(double v, int maxv)
{
	if (v < 0.0)
		v = 0.0;
	int r = (int)(v + 0.5);
	return r > maxv ? maxv : r;
}

// Straight RGBA16 (dnxhd_rgba16) -> the planes: limited range through the matrix with
// luma coefficients kr, kb; alpha dropped; 4:2:2 chroma is the mean of a horizontal pair's
// exact chroma (the last odd column takes its own). Each sample is rounded once.
void dnxhd_from_rgba16(DnxCtx *ctx, double kr, double kb)
{
	const uint16_t *rgba = ctx->rgba;
	if (!rgba)
		return;
	const double kg = 1.0 - kr - kb;
	const double s = ctx->bit_depth > 8 ? 4.0 : 1.0;
	const double yScale = 219.0 * s, yOff = 16.0 * s;
	const double cScale = 224.0 * s, cOff = 128.0 * s;
	const int maxv = (1 << ctx->bit_depth) - 1;
	const double cbDiv = 2.0 * (1.0 - kb), crDiv = 2.0 * (1.0 - kr);
	const int w = ctx->width, h = ctx->height;

	for (int y = 0; y < h; y++) {
		const uint16_t *p = rgba + (size_t)y * w * 4;
		double cbPrev = 0.0, crPrev = 0.0;
		for (int x = 0; x < w; x++) {
			double r = p[x * 4 + 0] / 65535.0, g = p[x * 4 + 1] / 65535.0, b = p[x * 4 + 2] / 65535.0;
			double yy = kr * r + kg * g + kb * b;
			double cb = (b - yy) / cbDiv, cr = (r - yy) / crDiv;
			int Y = round_clamp(yOff + yScale * yy, maxv);
			int cx = -1;
			double cbOut = 0.0, crOut = 0.0;
			if (ctx->is_444) {
				cx = x; cbOut = cb; crOut = cr;
			} else if (x & 1) {
				cx = x >> 1; cbOut = (cbPrev + cb) * 0.5; crOut = (crPrev + cr) * 0.5;
			} else if (x == w - 1) {
				cx = x >> 1; cbOut = cb; crOut = cr;
			}
			cbPrev = cb; crPrev = cr;
			if (ctx->bit_depth > 8) {
				((uint16_t *)(ctx->plane[0] + y * ctx->plane_stride[0]))[x] = (uint16_t)Y;
				if (cx >= 0) {
					((uint16_t *)(ctx->plane[1] + y * ctx->plane_stride[1]))[cx] = (uint16_t)round_clamp(cOff + cScale * cbOut, maxv);
					((uint16_t *)(ctx->plane[2] + y * ctx->plane_stride[2]))[cx] = (uint16_t)round_clamp(cOff + cScale * crOut, maxv);
				}
			} else {
				ctx->plane[0][y * ctx->plane_stride[0] + x] = (uint8_t)Y;
				if (cx >= 0) {
					ctx->plane[1][y * ctx->plane_stride[1] + cx] = (uint8_t)round_clamp(cOff + cScale * cbOut, maxv);
					ctx->plane[2][y * ctx->plane_stride[2] + cx] = (uint8_t)round_clamp(cOff + cScale * crOut, maxv);
				}
			}
		}
	}
}

// Encode the planes into one frame (a QuickTime sample). Returns its size in bytes
// (dnxhd_frame_size), or -1 when the rate control cannot fit the frame.
int dnxhd_encode(DnxCtx *ctx)
{
	uint8_t *buf = ctx->packet;
	int offset, i;

	// dnxhd_load_picture
	ctx->linesize = ctx->plane_stride[0];
	ctx->uvlinesize = ctx->plane_stride[1];
	ctx->dct_y_offset = ctx->linesize * 8;
	ctx->dct_uv_offset = ctx->uvlinesize * 8;
	for (i = 0; i < 3; i++)
		ctx->src[i] = ctx->plane[i];

	dnxhd_write_header(ctx, buf);

	if (dnxhd_encode_fast(ctx) < 0)
		return -1;

	dnxhd_setup_threads_slices(ctx);

	offset = 0;
	for (i = 0; i < ctx->mb_height; i++) {
		wb32(ctx->msip + i * 4, offset);
		offset += ctx->slice_size[i];
	}

	for (i = 0; i < ctx->mb_height; i++)
		dnxhd_encode_row(ctx, buf, i);

	memset(buf + ctx->data_offset + offset, 0, ctx->coding_unit_size - 4 - offset - ctx->data_offset);

	wb32(buf + ctx->coding_unit_size - 4, 0x600DC0DE);	// EOF
	return ctx->frame_size;
}

