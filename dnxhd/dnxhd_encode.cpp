static void get_pixels_8_c(int16_t *block, const uint8_t *pixels, ptrdiff_t stride)
{
	for (int i = 0; i < 8; i++) {
		for (int k = 0; k < 8; k++)
			block[k] = pixels[k];
		pixels += stride;
		block += 8;
	}
}

static void get_pixels_16_c(int16_t *block, const uint8_t *pixels, ptrdiff_t stride)
{
	for (int i = 0; i < 8; i++)
		memcpy(block + i * 8, pixels + i * stride, 16);
}

static void get_pixels(DnxCtx *ctx, int16_t *block, const uint8_t *pixels, ptrdiff_t stride)
{
	if (ctx->bit_depth > 8)
		get_pixels_16_c(block, pixels, stride);
	else
		get_pixels_8_c(block, pixels, stride);
}

// ff_emulated_edge_mc with src_x = src_y = 0: the w x h region of src, its last column and
// row repeated out to block_w x block_h. elem is the sample size in bytes.
static void emulated_edge(uint8_t *buf, const uint8_t *src, int buf_linesize, int src_linesize,
                          int block_w, int block_h, int w, int h, int elem)
{
	for (int y = 0; y < block_h; y++) {
		const uint8_t *row = src + (y < h ? y : h - 1) * src_linesize;
		uint8_t *dst = buf + y * buf_linesize;
		for (int x = 0; x < block_w; x++) {
			int sx = x < w ? x : w - 1;
			memcpy(dst + x * elem, row + sx * elem, elem);
		}
	}
}

